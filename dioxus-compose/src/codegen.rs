fn screaming_snake_case(name: &str) -> String {
    let mut output = String::new();
    for (index, character) in name.char_indices() {
        if character.is_ascii_uppercase() && index != 0 {
            output.push('_');
        }
        output.push(character.to_ascii_uppercase());
    }
    output
}

