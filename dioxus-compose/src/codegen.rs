pub fn generate_event_vector() -> Result<Vec<u8>, ProtocolError> {
    let events = [
        HostEvent {
            node_id: 7,
            handler_id: 11,
            payload: EventPayload::Clicked,
        },
        HostEvent {
            node_id: 8,
            handler_id: 12,
            payload: EventPayload::TextChanged("한글"),
        },
        HostEvent {
            node_id: 8,
            handler_id: 13,
            payload: EventPayload::TextSubmitted("done"),
        },
        HostEvent {
            node_id: 8,
            handler_id: 14,
            payload: EventPayload::FocusLost,
        },
        HostEvent {
            node_id: 0,
            handler_id: 0,
            payload: EventPayload::ProtocolError {
                code: 9,
                message: "bad tag",
            },
        },
    ];
    let mut output = Vec::new();
    let mut encoded = Vec::new();
    for event in &events {
        encode_event(event, &mut encoded)?;
        output.extend_from_slice(&encoded);
    }
    Ok(output)
}

