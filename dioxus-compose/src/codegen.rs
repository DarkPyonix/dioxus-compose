fn write_enum(output: &mut String, name: &str, variants: &[crate::schema::EnumVariantSchema]) {
    write!(output, "enum class {name} {{ ").unwrap();
    for (index, variant) in variants.iter().enumerate() {
        if index != 0 {
            output.push_str(", ");
        }
        output.push_str(variant.name);
    }
    output.push_str(" }\n\n");
}

fn kotlin_type(ty: FieldType) -> &'static str {
    match ty {
        FieldType::Float => "kotlin.Float",
        FieldType::U32 => "Int",
        FieldType::U64 => "Long",
    }
}

fn modifier_decode_expression(ty: FieldType, source: &str) -> &'static str {
    match (ty, source) {
        (FieldType::Float, "first") => "kotlin.Float.fromBits(first.toInt())",
        (FieldType::Float, "second") => "kotlin.Float.fromBits(second.toInt())",
        (FieldType::U32, "first") => "first.toInt()",
        (FieldType::U32, "second") => "second.toInt()",
        (FieldType::U64, "first") => "first",
        (FieldType::U64, "second") => "second",
        _ => unreachable!(),
    }
}
