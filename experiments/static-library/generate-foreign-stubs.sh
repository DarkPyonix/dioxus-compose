#!/usr/bin/env bash
# Writes definitions for the Skia entry points this platform does not have.
#
# Usage: ./generate-foreign-stubs.sh <built renderer> <static skiko archive> <output.c>
#
# Skiko declares every platform's native methods in one Kotlin source set: the Direct3D
# ones, the X11 ones and the Metal ones all exist as declarations everywhere. Only the
# ones for the platform being built are compiled, which is correct and is not a problem
# while the library is loaded at run time, because a name is looked up when it is first
# called and the ones belonging to another platform never are.
#
# Linking it into the image changes that. The image now refers to every declared native
# method by symbol, so the ones this platform does not implement are undefined, and macOS
# binds everything at load, so the process dies on the first of them before drawing
# anything.
#
# They are still never called. So each one is defined here as something that says where it
# came from and stops, which is what calling a Direct3D entry point on macOS deserves.
set -euo pipefail

renderer="${1:?usage: $0 <renderer> <archive> <output.c>}"
archive="${2:?}"
output="${3:?}"

defined="$(nm -g "$archive" | awk '$2 == "T" { print substr($3, 2) }' | sort -u)"
undefined="$(nm -u "$renderer" | sed 's/^_//' | grep '^Java_org_jetbrains_ski' | sort -u)"
foreign="$(comm -23 <(echo "$undefined") <(echo "$defined"))"

count="$(echo "$foreign" | grep -c . || true)"
{
    echo "// Generated by experiments/static-library/generate-foreign-stubs.sh. DO NOT EDIT."
    echo "//"
    echo "// The Skia entry points belonging to other platforms. See that script for why"
    echo "// they have to exist at all when Skia is linked into the image."
    echo "#include <stdio.h>"
    echo "#include <stdlib.h>"
    echo ""
    echo "static void dioxus_compose_foreign_entry_point(const char *name) {"
    echo "    fprintf(stderr,"
    echo "            \"dioxus-compose: %s belongs to another platform's graphics stack and \""
    echo "            \"cannot run here. Reaching it means the renderer chose a drawing path \""
    echo "            \"that does not exist on this system.\\\\n\","
    echo "            name);"
    echo "    abort();"
    echo "}"
    echo ""
    while IFS= read -r symbol; do
        [[ -n "$symbol" ]] || continue
        echo "void $symbol(void) { dioxus_compose_foreign_entry_point(\"$symbol\"); }"
    done <<< "$foreign"
} > "$output"

echo "wrote $output"
echo "  $count entry points from other platforms"
